"""Command-line entry points for CS180 Project 4A."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from mosaic import (
    computeH,
    load_image,
    make_mosaic,
    save_image,
    select_correspondences,
    show_correspondences,
    warp_image,
)


def save_points(path: str, source: np.ndarray, destination: np.ndarray) -> None:
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump({"source_points": source.tolist(), "destination_points": destination.tolist()}, handle, indent=2)


def load_points(path: str) -> tuple[np.ndarray, np.ndarray]:
    with open(path, encoding="utf-8") as handle:
        data = json.load(handle)
    return np.asarray(data["source_points"], dtype=float), np.asarray(data["destination_points"], dtype=float)


def pick_command(args: argparse.Namespace) -> None:
    source_image, destination_image = load_image(args.source), load_image(args.destination)
    source, destination = select_correspondences(source_image, destination_image, args.count)
    save_points(args.output, source, destination)
    visualization = Path(args.output).with_suffix(".png")
    show_correspondences(source_image, destination_image, source, destination, visualization)
    print(f"Saved point pairs to {args.output}")
    print(f"Saved correspondence visualization to {visualization}")


def rectify_command(args: argparse.Namespace) -> None:
    image = load_image(args.image)
    if args.points:
        source, _ = load_points(args.points)
    else:
        plt.figure(figsize=(10, 7))
        plt.imshow(image)
        plt.title("Click rectangle corners: top-left, top-right, bottom-right, bottom-left")
        source = np.asarray(plt.ginput(4, timeout=0), dtype=float)
        plt.close()
    if source.shape != (4, 2):
        raise ValueError("Rectification needs exactly four clicked corners.")
    width = args.width or int(round((np.linalg.norm(source[1] - source[0]) + np.linalg.norm(source[2] - source[3])) / 2))
    height = args.height or int(round((np.linalg.norm(source[3] - source[0]) + np.linalg.norm(source[2] - source[1])) / 2))
    destination = np.array([[0, 0], [width - 1, 0], [width - 1, height - 1], [0, height - 1]], dtype=float)
    H = computeH(source, destination)
    rectified, _ = warp_image(image, H, (height, width), args.method)
    save_image(args.output, rectified)
    print(f"Saved rectified image to {args.output}")
    print("Homography (source -> rectangle):\n", H)


def mosaic_command(args: argparse.Namespace) -> None:
    image_paths = args.images
    images = [load_image(path) for path in image_paths]
    homographies = [np.eye(3)]
    records: list[dict[str, object]] = []
    reference = images[0]
    for index, source_image in enumerate(images[1:], start=1):
        print(f"Select {args.count} matches: {image_paths[index]} -> reference {image_paths[0]}")
        source, destination = select_correspondences(source_image, reference, args.count)
        H = computeH(source, destination)
        homographies.append(H)
        records.append({"image": image_paths[index], "source_points": source.tolist(), "reference_points": destination.tolist(), "homography": H.tolist()})
        diagnostic = Path(args.output).with_name(f"{Path(args.output).stem}_matches_{index}.png")
        show_correspondences(source_image, reference, source, destination, diagnostic)
        print(f"Saved match diagnostic to {diagnostic}")
    mosaic = make_mosaic(images, homographies, args.method)
    save_image(args.output, mosaic)
    if args.save_data:
        Path(args.save_data).parent.mkdir(parents=True, exist_ok=True)
        with open(args.save_data, "w", encoding="utf-8") as handle:
            json.dump({"reference_image": image_paths[0], "matches": records}, handle, indent=2)
    print(f"Saved mosaic to {args.output}")


def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="CS180 Project 4A image warping and mosaicing")
    commands = parser.add_subparsers(dest="command", required=True)

    pick = commands.add_parser("pick", help="Click and save corresponding points for two images")
    pick.add_argument("source")
    pick.add_argument("destination")
    pick.add_argument("--output", required=True, help="JSON output path")
    pick.add_argument("--count", type=int, default=8, help="Number of matches (use >= 4)")
    pick.set_defaults(func=pick_command)

    rectify = commands.add_parser("rectify", help="Click four corners and rectify a planar object")
    rectify.add_argument("image")
    rectify.add_argument("--output", required=True)
    rectify.add_argument("--points", help="Optional JSON generated by pick; uses source_points")
    rectify.add_argument("--width", type=int, help="Optional rectified output width")
    rectify.add_argument("--height", type=int, help="Optional rectified output height")
    rectify.add_argument("--method", choices=("nearest", "bilinear"), default="bilinear")
    rectify.set_defaults(func=rectify_command)

    mosaic = commands.add_parser("mosaic", help="Interactively compute and blend a mosaic")
    mosaic.add_argument("--images", nargs="+", required=True, help="Reference image first, then images to warp into it")
    mosaic.add_argument("--output", required=True)
    mosaic.add_argument("--count", type=int, default=8, help="Number of matches per image (use >= 4)")
    mosaic.add_argument("--method", choices=("nearest", "bilinear"), default="bilinear")
    mosaic.add_argument("--save-data", help="Optional JSON location for homographies and point matches")
    mosaic.set_defaults(func=mosaic_command)
    return parser


if __name__ == "__main__":
    arguments = make_parser().parse_args()
    arguments.func(arguments)
